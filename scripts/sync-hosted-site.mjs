// MatchMaker is the source of truth. Copy only reviewed source files, never credentials.
import {mkdirSync,copyFileSync,readFileSync,writeFileSync,readdirSync} from 'node:fs';
import {resolve,dirname} from 'node:path';
const root=resolve(import.meta.dirname,'..');
const site=resolve(root,'../sites/thread-wardrobe');
const target=resolve(site,'matchmaker/phone');
mkdirSync(target,{recursive:true});
const files=['App.js','Frame.js','Frame.web.js','PhotoCrop.js','PhotoCrop.web.js','ai-connection.web.js','save-photo.js','save-photo.web.js','storage.js','storage.web.js','migrate-wardrobe.mjs','crop-pixels.mjs','crop-editor.mjs','crop-runtime.generated.js','index.js','app.json','package.json','package-lock.json','assets.d.ts'];
for(const name of files)copyFileSync(resolve(root,'phone',name),resolve(target,name));
mkdirSync(resolve(target,'assets'),{recursive:true});
for(const name of readdirSync(resolve(root,'phone/assets')))copyFileSync(resolve(root,'phone/assets',name),resolve(target,'assets',name));
writeFileSync(resolve(target,'metro.config.js'),"const {getDefaultConfig}=require('expo/metro-config');module.exports=getDefaultConfig(__dirname);\n");
const server=resolve(site,'matchmaker/server');mkdirSync(server,{recursive:true});
copyFileSync(resolve(root,'helper/validate.mjs'),resolve(server,'validate.mjs'));
let key=readFileSync(resolve(root,'helper/get-key.mjs'),'utf8');
key=key.replace("import {readFileSync} from 'node:fs';\nimport {parseEnv} from 'node:util';",'let runtime;\nexport function configureKeys(env){runtime=env;}');
const start=key.indexOf('  let env;'),end=key.indexOf('  secrets.add(env.KEYGEN_TOKEN);');
if(start<0||end<start)throw Error('Review key helper before syncing');
key=key.slice(0,start)+'  const env=runtime;\n'+key.slice(end);
key=key.replace("redirect:'error'","redirect:'manual'");
writeFileSync(resolve(server,'get-key.mjs'),key);
const brief=readFileSync(resolve(root,'BRIEF.md'),'utf8');
const model=readFileSync(resolve(root,'NOTES.md'),'utf8').match(/^AI model:\s*(\S+)/m)[1];
let ai=readFileSync(resolve(root,'helper/ask-ai.mjs'),'utf8');
ai=ai.replace("import {readFileSync} from 'node:fs';\n",'');
const configStart=ai.indexOf('const root='),configEnd=ai.indexOf('export async function askAI');
ai=ai.slice(0,configStart)+`export function configuration(){return {model:${JSON.stringify(model)}};}\n`+ai.slice(configEnd);
ai=ai.replace(" const brief=readFileSync(new URL('BRIEF.md',root),'utf8');\n const instructions=brief.split('## My AI’s instructions')[1];",` const instructions=${JSON.stringify(brief.split('## My AI’s instructions')[1])};`);
if(ai.includes('readFileSync'))throw Error('Unexpected file access in hosted AI');
writeFileSync(resolve(server,'ask-ai.mjs'),ai);
console.log('Synced MatchMaker interface and AI instructions; no secrets copied.');
